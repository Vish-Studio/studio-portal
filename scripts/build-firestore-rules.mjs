import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const ruleFiles = [
  'firestore-rules/00-header.rules',
  'firestore-rules/01-helpers.rules',
  'firestore-rules/collections/users.rules',
  'firestore-rules/collections/projects.rules',
  'firestore-rules/collections/documents.rules',
  'firestore-rules/collections/messages.rules',
  'firestore-rules/collections/tasks.rules',
  'firestore-rules/collections/expenses.rules',
  'firestore-rules/collections/clients.rules',
  'firestore-rules/collections/team.rules',
  'firestore-rules/collections/team-members-legacy.rules',
  'firestore-rules/collections/sign-in-access.rules',
  'firestore-rules/collections/settings.rules',
  'firestore-rules/99-footer.rules',
];

const generatedNotice = [
  '// Generated by scripts/build-firestore-rules.mjs.',
  '// Edit files in firestore-rules/ instead of editing this file directly.',
  '',
].join('\n');

const contents = ruleFiles
  .map(file => readFileSync(resolve(root, file), 'utf8').trimEnd())
  .join('\n\n');

writeFileSync(resolve(root, 'firestore.rules'), `${generatedNotice}${contents}\n`);
